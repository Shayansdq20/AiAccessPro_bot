export type Dict = typeof en;
const dicts: Record<AdminLang, Dict> = { en, fa };

export async function getLang(): Promise<AdminLang> {
  const value = (await cookies()).get(LANG_COOKIE)?.value;
  return value === 'en' ? 'en' : 'fa';
}

export async function getDict(): Promise<{ t: Dict; lang: AdminLang; dir: 'rtl' | 'ltr' }> {
  const lang = await getLang();
  return { t: dicts[lang], lang, dir: lang === 'fa' ? 'rtl' : 'ltr' };
}
